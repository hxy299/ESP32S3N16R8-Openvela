#!/usr/bin/env bash
#
# install-btsh-light.sh — 安装 BLE GATT 灯控服务应用到 apps 树
#
# ## 为什么需要
#
# 该应用是本项目**自己写的**（不在上游 apps 里），需要放进
# `apps/wireless/bluetooth/` 才能被 NuttX 构建系统收录。
#
# 这里采用「安装 + 幂等」的方式，而不是直接改上游源码：
#   - 权威副本保存在本仓库 `src/app/`
#   - 脚本负责同步到 apps 树并挂钩子
#   - 支持 --check / --revert
#
# ## 安装内容
#
#   1. src/app/{btsh_light_main.c,Makefile,Make.defs,Kconfig}
#      -> apps/wireless/bluetooth/btsh_light/
#
#   2. apps/wireless/bluetooth/Make.defs 追加：
#        include $(APPDIR)/wireless/bluetooth/btsh_light/Make.defs
#
#   3. apps/wireless/bluetooth/Kconfig 追加：
#        source "$APPDIR/wireless/bluetooth/btsh_light/Kconfig"
#
# ## 用法
#
#   bash scripts/setup/install-btsh-light.sh           # 安装
#   bash scripts/setup/install-btsh-light.sh --check   # 检查
#   bash scripts/setup/install-btsh-light.sh --revert  # 撤销
#
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
OPENVELA_ROOT="${OPENVELA_ROOT:-$HOME/openvela}"

SRC_DIR="$PROJECT_ROOT/src/app"
APPS_DIR="$OPENVELA_ROOT/apps"
DST_DIR="$APPS_DIR/wireless/bluetooth/btsh_light"
BT_MAKEDEFS="$APPS_DIR/wireless/bluetooth/Make.defs"
BT_KCONFIG="$APPS_DIR/wireless/bluetooth/Kconfig"

FILES="btsh_light_main.c Makefile Make.defs Kconfig"

MAKE_ANCHOR='$(APPDIR)/wireless/bluetooth/btsh_light/Make.defs'
KCONF_ANCHOR='wireless/bluetooth/btsh_light/Kconfig'

ok()   { printf '  \033[32m✓\033[0m %s\n' "$1"; }
warn() { printf '  \033[33m!\033[0m %s\n' "$1"; }
bad()  { printf '  \033[31m✗\033[0m %s\n' "$1"; }
info() { printf '\033[36m%s\033[0m\n' "$1"; }

check_state() {
  echo "btsh_light 安装状态："
  if [ -d "$DST_DIR" ]; then
    for f in $FILES; do
      [ -f "$DST_DIR/$f" ] && ok "$f" || warn "$f 缺失"
    done
    # 校验内容是否与权威副本一致
    for f in $FILES; do
      if [ -f "$DST_DIR/$f" ] && ! cmp -s "$SRC_DIR/$f" "$DST_DIR/$f"; then
        warn "$f 与仓库副本不一致（需重跑安装）"
      fi
    done
  else
    warn "目标目录不存在：$DST_DIR"
  fi
  # Make.defs 靠 apps/wireless/bluetooth/Make.defs 的通配符自动收录
  if grep -q "btsh_light/Make.defs" "$BT_MAKEDEFS" 2>/dev/null; then
    warn "Make.defs 存在多余手工挂钩（应删除，通配符已覆盖）"
  else
    ok "Make.defs 靠通配符自动收录（无需挂钩）"
  fi
  grep -q "btsh_light/Kconfig" "$BT_KCONFIG" 2>/dev/null \
    && ok "Kconfig 已挂钩" || warn "Kconfig 未挂钩"
}

case "${1:-}" in
  --check) check_state; exit 0 ;;
  --revert)
    info "撤销 btsh_light 安装"
    [ -d "$DST_DIR" ] && rm -rf "$DST_DIR" && ok "已删除 $DST_DIR"
    # Make.defs 靠通配符，无需处理；但清理可能存在的历史手工挂钩
    sed -i "\|btsh_light/Make.defs|d" "$BT_MAKEDEFS" 2>/dev/null || true
    if grep -q "btsh_light/Kconfig" "$BT_KCONFIG" 2>/dev/null; then
      sed -i "\|btsh_light/Kconfig|d" "$BT_KCONFIG"
      ok "已移除 Kconfig 挂钩"
    fi
    check_state
    exit 0 ;;
esac

info "安装 btsh_light 到 apps 树"

[ -d "$APPS_DIR/wireless/bluetooth" ] || {
  bad "找不到 $APPS_DIR/wireless/bluetooth"; exit 1; }
for f in $FILES; do
  [ -f "$SRC_DIR/$f" ] || { bad "缺少源文件 $SRC_DIR/$f"; exit 1; }
done

# ------------------------------------------------------------------ 1. 拷贝
mkdir -p "$DST_DIR"
CHANGED=0
for f in $FILES; do
  if [ -f "$DST_DIR/$f" ] && cmp -s "$SRC_DIR/$f" "$DST_DIR/$f"; then
    ok "$f 已是最新"
  else
    cp "$SRC_DIR/$f" "$DST_DIR/$f"
    ok "$f 已安装"
    CHANGED=1
  fi
done

# ------------------------------------------------------------------ 2. Make.defs
#
# ★ 无需挂钩！apps/wireless/bluetooth/Make.defs 末尾本来就有通配符：
#     include $(wildcard $(APPDIR)/wireless/bluetooth/*/Make.defs)
#   只要 btsh_light/Make.defs 存在于该目录下就会被自动收录。
#   （早期版本我手工追加了一行，导致 make 报
#    "overriding recipe for target ... _all" 重复定义警告。）
#
#   这里只做一件事：清理历史遗留的手工挂钩。
if grep -q "btsh_light/Make.defs" "$BT_MAKEDEFS" 2>/dev/null; then
  warn "发现多余的手工 Make.defs 挂钩，清理（通配符已覆盖）"
  sed -i "\|btsh_light/Make.defs|d" "$BT_MAKEDEFS"
  # 顺手删掉我加的两行注释
  sed -i "\|BLE GATT 灯控服务（OpenvelaESP-BTSH 项目）|d" "$BT_MAKEDEFS"
  sed -i "\|见 scripts/setup/install-btsh-light.sh|d" "$BT_MAKEDEFS"
  ok "已清理，依赖通配符自动收录"
else
  ok "Make.defs 无需挂钩（通配符自动收录）"
fi

# ------------------------------------------------------------------ 3. Kconfig
#
# ★ Kconfig 必须手工 source。
#   注意两点：
#     1) apps/wireless/bluetooth/Kconfig 是**自动生成**的
#        （文件头写着 "This file is autogenerated, do not edit."），
#        但构建时不会被覆盖，所以追加是安全的。
#     2) **不能用 $APPDIR 变量** —— kconfig 解析时该变量为空，
#        会报 "not found (in 'source "$APPDIR/...")"。
#        官方用的就是**绝对路径**：
#          source "/home/.../apps/wireless/bluetooth/btsak/Kconfig"
#
if grep -q "btsh_light/Kconfig" "$BT_KCONFIG" 2>/dev/null; then
  ok "Kconfig 已挂钩"
else
  cat >> "$BT_KCONFIG" <<EOF

# BLE GATT 灯控服务（OpenvelaESP-BTSH 项目）
# 由 scripts/setup/install-btsh-light.sh 添加；用绝对路径（kconfig 不展开变量）
source "$DST_DIR/Kconfig"
EOF
  ok "Kconfig 已追加挂钩（绝对路径）"
fi

echo
check_state
echo
echo "下一步：在 defconfig 里加 CONFIG_BTSH_LIGHT=y 后构建"
